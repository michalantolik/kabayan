const state = {
  language: "en"
};

const byPath = (object, path) => path.split(".").reduce((value, key) => value?.[key], object);

function setLanguage(language) {
  const copy = translations[language];
  if (!copy) return;

  state.language = language;
  document.documentElement.lang = language;
  document.title = copy.meta.title;
  document.querySelector('meta[name="description"]').content = copy.meta.description;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = byPath(copy, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = byPath(copy, element.dataset.i18nAriaLabel);
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = byPath(copy, element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.placeholder = value;
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });

}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});
